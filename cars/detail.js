/* ========== Init ========== */
document.addEventListener('DOMContentLoaded', () => {
    document.documentElement.classList.add('js-enabled');

    const pageKey = getPageKey();
    const savedLang = localStorage.getItem('tns-lang') || 'zh';
    applyDetailLang(savedLang, pageKey);

    document.getElementById('langSwitch').addEventListener('click', () => {
        const next = (localStorage.getItem('tns-lang') || 'zh') === 'zh' ? 'en' : 'zh';
        localStorage.setItem('tns-lang', next);
        applyDetailLang(next, pageKey);
    });

    /* Scroll fade-up */
    const fadeEls = document.querySelectorAll('.fade-up, .detail-hero-tagline, .detail-hero-name, .detail-hero-sub, .detail-hero-badge');
    fadeEls.forEach(el => {
        const r = el.getBoundingClientRect();
        if (r.top < window.innerHeight && r.bottom > 0) el.classList.add('visible');
    });
    const obs = new IntersectionObserver(entries => {
        entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('visible'); });
    }, { threshold: 0.08, rootMargin: '0px 0px -20px 0px' });
    fadeEls.forEach(el => obs.observe(el));
});

function getPageKey() {
    const path = window.location.pathname;
    if (path.includes('rz-01')) return 'rz';
    if (path.includes('ur-01')) return 'ur';
    if (path.includes('h-01')) return 'h';
    return 'gt';
}

function applyDetailLang(lang, pageKey) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (DETAIL_I18N[lang] && DETAIL_I18N[lang][key]) {
            el.textContent = DETAIL_I18N[lang][key];
        }
    });
    document.getElementById('langLabel').textContent = lang === 'zh' ? 'EN' : '中文';
}
